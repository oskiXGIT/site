// Sitam faile atskirai issaugom extra kalba, kad ji isliktu po refresh.
const extraLanguageSelect = document.getElementById('languageSelect');
const savedExtraLang = localStorage.getItem('oskiExtraLang');

extraLanguageSelect.addEventListener('change', (event) => {
  const lang = event.target.value;
  if (lang === 'zh' || lang === 'ru') localStorage.setItem('oskiExtraLang', lang);
  else localStorage.removeItem('oskiExtraLang');
});

if (savedExtraLang === 'zh' || savedExtraLang === 'ru') {
  applyLanguage(savedExtraLang);
}
